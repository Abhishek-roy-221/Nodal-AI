from pydantic import BaseModel, Field

from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(...,description="list of messages to be processed to be processed by agent")
    curated_ques : str = Field(...,description="Curated user question")
    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context that will help agent to generate SQL query")
    is_safe : Literal["Yes","No"] = Field(..., description="Indicates whether the generated SQL query is safe to exexute or not")
    generated_sql_query : str = Field(..., description="SQL query generated by the agent")
    final_answer : str = Field(..., description="The final answer generated by the agent based on the SQL query")    